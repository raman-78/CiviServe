def localize(message: str, language: str, **kwargs: Any) -> str:
    """Return ``message`` in ``language``, English fallback, with ``format`` args."""
    entry = _CATALOG.get(message, {})
    text = entry.get(language) or entry.get(FALLBACK_LANGUAGE) or message
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return text
    return text


def has_translation(message: str, language: str) -> bool:
    return language in _CATALOG.get(message, {})
